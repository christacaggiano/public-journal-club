// Generates docs/METHODS.md from config/rubric.json, so the published methods always match
// the rubric the app actually uses. Run with `npm run docs` after editing the rubric.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const rubric = JSON.parse(readFileSync(path.join(root, "config", "rubric.json"), "utf8"));
const cite = (id) => {
  const c = rubric.citations[id];
  if (!c) throw new Error(`Unknown citation id "${id}" in config/rubric.json`);
  return `[${c.short}](${c.url})`;
};
const claimIds = rubric.claim_types.map((c) => c.id);
const ratingIds = ["rigor", "bias", "effect", "value"];

const lines = [];
const out = (...l) => lines.push(...l);

out(
  "# Methods: how Public Journal Club reviews a paper",
  "",
  `<!-- Generated by scripts/build-methods-doc.mjs from config/rubric.json (rubric version ${rubric.version}). Edit those files, not this one, then run \`npm run docs\`. -->`,
  "",
  `Rubric version: **${rubric.version}**. Every saved review records the rubric version it was rated with (\`rubric_version\` in its \`review.json\`).`,
  "",
  "This document is for scientists who want to check how reviews are produced. Reviews are written by large language models (Claude). They are a teaching aid that models how scientists weigh evidence, not a substitute for expert appraisal. The rubric below constrains the models, and several steps are checked by deterministic code rather than left to the model.",
  "",
  "## Pipeline",
  "",
  "1. **Text extraction.** The PDF's text is extracted (`unpdf`) so quotes can be verified later, and the paper's DOI is read from its first two pages.",
  "2. **Publication status (deterministic).** The DOI is looked up in the Crossref REST API, which includes the Retraction Watch database. Retractions, withdrawals, expressions of concern and corrections are read from the paper's `updated-by` relations and from notices whose `update-to` points at the paper. Crossref records of type `posted-content` are reported as preprints. See " + cite("crossref_rw") + ".",
  "3. **Background check (Sonnet, 2 web searches).** Paper details, the authors' financial or professional stakes in the result, the journal's standing, and earlier work or replication attempts.",
  "4. **Critique (Opus, no web search, with a code sandbox)** and, at the same time, **context (Sonnet, 2 web searches)**. The critique classifies the paper, writes the highlights, and scores the four ratings using the rubric below. The context step writes the plain-language summary and compares the findings with related research.",
  "5. **Server-side checks.** The cap on \"evidence for the main claim\" is applied in code (the model's score is lowered if it exceeds the cap, and the original score is kept as `capped_from`). Every quoted passage is matched against the PDF text; unmatched quotes get one repair attempt and are otherwise flagged as unverified and not highlighted. Claims that a number was recomputed with code are kept only if the model actually ran code during the critique.",
  "6. **Glossary (Sonnet).** Plain definitions for terms used in the finished review.",
  "",
  "## Step 1: classify the paper",
  "",
  "The critique first records the paper's **evidence type** (its design), its **main claim** in one sentence, the **type of claim**, and the **population** studied. It also flags **overreach**: a main claim that goes beyond what the design can support.",
  "",
  "| Claim type | Meaning |",
  "|---|---|",
  ...rubric.claim_types.map((c) => `| ${c.label} (\`${c.id}\`) | ${c.description} |`),
  "",
  "## Step 2: caps by design and claim",
  "",
  "\"Evidence for the main claim\" can never exceed the cap for the paper's evidence type and claim type. The cap expresses what the best possible study of that design could show for that kind of claim. The score then starts from the cap and is lowered for flaws, imprecision, or conflict with other research, in the spirit of " + cite("grade") + " and the " + cite("ocebm") + ".",
  "",
  `| Evidence type | ${rubric.claim_types.map((c) => c.label).join(" | ")} | Appraisal tools |`,
  `|---|${claimIds.map(() => "---").join("|")}|---|`,
  ...rubric.evidence_types.map((t) => `| ${t.label} | ${claimIds.map((c) => t.caps[c]).join(" | ")} | ${t.tools.map(cite).join(", ")} |`),
  "",
  ...rubric.evidence_types.filter((t) => t.cap_note).map((t) => `- **${t.label}:** ${t.cap_note}`),
  "",
  "## Step 3: checklists by design",
  "",
  "Study quality is judged against the best version of the paper's own design, using a short checklist drawn from the established appraisal tool for that design. The checklists are deliberately brief, plain-language paraphrases; they are not substitutes for the full tools.",
  "",
);
for (const t of rubric.evidence_types) {
  out(`### ${t.label}`, "", `${t.examples} Based on ${t.tools.map(cite).join(", ")}.`, "", ...t.checklist.map((q) => `- ${q}`), "");
}

out("## Step 4: the four ratings", "", "Each rating is scored from 0 to 5 in steps of 0.5 against fixed anchors.", "");
for (const id of ratingIds) {
  const r = rubric.ratings[id];
  out(
    `### ${r.label} (\`${id}\`, higher is ${r.higher_is})`,
    "",
    r.definition + (r.tools.length ? ` See ${r.tools.map(cite).join(", ")}.` : ""),
    "",
    "| Score | Meaning |",
    "|---|---|",
    ...["5", "4", "3", "2", "1", "0"].filter((k) => r.anchors[k]).map((k) => `| ${k} | ${r.anchors[k]} |`),
    "",
  );
}
out(
  `Study quality and the risk of slanted reporting are scored separately on purpose: the first covers how the study was run, the second covers conflicts of interest, selective reporting and spin, which a well-run study can still have. Each review must also include at least ${rubric.min_strengths} genuine strengths.`,
  "",
  "## Recomputing reported numbers",
  "",
  "Statistical reporting errors are common and can be detected by recomputing reported values from the paper's own numbers (" + cite("statcheck") + "; " + cite("grim") + "). Before a review says a reported number is wrong, the critique model must recompute it, using a code sandbox for anything beyond simple arithmetic. Each such note shows what the paper reported, the inputs, the method and the result, and whether code was used. If code was not actually run during the critique, the note is shown as checked by hand.",
  "",
  "## Limitations",
  "",
  "- Ratings are model judgments guided by the rubric. They have not yet been validated against independent expert raters; a planned calibration set (a randomized trial, a meta-analysis, an observational study, an animal study and a genetic association study) is the next step.",
  "- The caps are the authors' judgment, informed by the cited frameworks, and are open to revision.",
  "- Background checks rely on what web search finds; undisclosed conflicts of interest can be missed.",
  "- Publication status depends on Crossref and Retraction Watch coverage and on the DOI being present in the PDF.",
  "",
  "## Changing the rubric",
  "",
  "Everything above comes from `config/rubric.json`: claim types, evidence types, checklists, caps, rating definitions, anchors and citations. To change it, edit that file, bump its `version`, and run `npm run docs` to regenerate this document. The app validates the file at startup and refuses to run if, for example, an evidence type is missing a cap or cites an unknown reference. Bumping the version means each paper gets a fresh review the next time it is uploaded.",
  "",
  "## References",
  "",
  ...Object.values(rubric.citations).map((c) => `- ${c.full} ${c.url}`),
  "",
);

mkdirSync(path.join(root, "docs"), { recursive: true });
writeFileSync(path.join(root, "docs", "METHODS.md"), lines.join("\n"));
console.log(`Wrote docs/METHODS.md (rubric version ${rubric.version})`);
